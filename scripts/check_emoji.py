FLAGGED = {0xFE0F}
for r in EMOJI:
    FLAGGED.update(range(r[0], r[1] + 1) if isinstance(r, tuple) else (r,))

ROOT = Path(__file__).resolve().parent.parent
SUFFIXES = (".js", ".mjs", ".css", ".html", ".json", ".svg")


def files():
    for folder in ("map-viewer", "atlas"):
        for p in sorted((ROOT / folder).rglob("*")):
            parts = p.relative_to(ROOT).parts
            if p.is_file() and p.suffix in SUFFIXES and "vendor" not in parts and "fixtures" not in parts:
                yield p


def finds(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    for n, line in enumerate(text.splitlines(), 1):
        for ch in line:
            if ord(ch) in FLAGGED:
                yield n, ch


def main(args):
    if args == ["--self-test"]:
        ok = 0x21A9 in FLAGGED and 0x21C9 not in FLAGGED and 0x21BB not in FLAGGED and ord("3") not in FLAGGED
        print("emoji: self-test " + ("OK" if ok else "FAILED"))
        return 0 if ok else 1
    paths = [Path(a) for a in args] or list(files())
    bad = 0
    for p in paths:
        for n, ch in finds(p):
            rel = p.resolve().relative_to(ROOT) if p.resolve().is_relative_to(ROOT) else p
            print(f"emoji: {rel}:{n}: U+{ord(ch):04X} has an emoji form; draw an icon instead")
            bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
