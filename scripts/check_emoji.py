#!/usr/bin/env python3
"""check_emoji.py: no character a system may draw as an emoji in the viewer or the atlas.

Some symbols have an emoji form (the return mark U+21A9 shows as an emoji on iPhone
Safari). Such a character in map-viewer/ or atlas/ is a problem; draw an icon instead.
Flagged: every non-ASCII code point with Emoji_Presentation, every base of an emoji
variation sequence (Unicode 18.0 emoji-data.txt and emoji-variation-sequences.txt; ASCII
keycap bases left out), and U+FE0F itself. Test fixtures and vendor/ are not read.

  python3 scripts/check_emoji.py              check the tree, exit 1 on a find
  python3 scripts/check_emoji.py FILE...      check these files only
  python3 scripts/check_emoji.py --self-test  the list holds U+21A9 and not U+21C9, U+21BB
"""
